/// Renders what this build can do, as markdown.
///
/// Written to `docs/capabilities.md` by `tool/generate_capabilities.dart` and
/// checked by `test/tools/capabilities_test.dart`, so the document is a
/// consequence of the code rather than a description of it that someone has to
/// remember to update.
///
/// Schema, not data. It resolves the cores against a synthetic one-package
/// project, so what comes out is the shape every project gets — the actions and
/// their parameters — and not this repo's entry ids or dependency names. Those
/// belong to `fw run … entries` and `fw run … list`, which is rather the point:
/// a capability document that listed the data would be describing one project.
String renderCapabilities({
  PluginCoreRegistry? registry,
  Map<String, ResultShape>? shapes,
}) {
  var cores = _resolve(registry ?? defaultCoreRegistry());
  var sections = [
    _header,
    _cliSection(),
    _mcpSection(),
    _actionsSection(cores, shapes ?? resultShapes),
  ];
  return '${sections.map((section) => section.trim()).join('\n\n')}\n';
}

/// The plugin ids this build knows, resolved against a project that declares
/// all of them and one package.
List<PluginCore> _resolve(PluginCoreRegistry registry) {
  const worktree = Worktree(path: '/project');
  var workspace = Workspace(
    root: worktree.path,
    declared: const [Pkg('.')],
    discovered: const ['.'],
    appContext: AppContext(logger: LogClient.print()),
    flutterSdk: FlutterSdkPath('/flutter'),
  );
  var manifest = PluginManifest([
    for (var id in registry.ids)
      PluginDeclaration(
        id: id,
        label: id.split('.').last,
        config:
            _sampleConfigs[id] ??
            const {
              'packages': [
                {'path': '.'},
              ],
            },
      ),
  ]);
  return Session.resolved(
    worktree: worktree,
    workspace: workspace,
    manifest: manifest,
    registry: registry,
  ).cores;
}

/// What a plugin has to be declared with before it has anything to say, for
/// the plugins where the default package list is not enough.
///
/// Almost every plugin's actions are static: it declares the same ones whether
/// the project gave it one package or ten, so a bare package list resolves a
/// complete answer. The dev stack is the exception — its actions are one set
/// **per declared service**, so against a project that declares none it
/// truthfully reports nothing, and the document loses the plugin entirely.
/// That reads as a decision rather than the omission it is, which is the same
/// failure this generator's `shapeSources` comment warns about.
///
/// One delegated service, with the transitions, so the document lists exactly
/// the three every service has. A project's own `commands:` add one action
/// each on top, and naming an invented one here would document an action
/// nobody has.
///
/// Deliberately not two, and deliberately not owned. Two services would
/// document the `<id>.`-prefixed ids, which a project declaring one — the
/// common case — does not have; an owned one would document its free `logs`
/// and describe `start` as a spawn, which a delegated service's is not. The
/// document takes the shape every declaration shares, and the extras are on
/// `fw run dev_stack` and `flutterware_actions` against the real project,
/// where they are true.
final _sampleConfigs = <String, Map<String, Object?>>{
  devStackPluginId: DevStack.background(
    probe: const Probe.exitCode(StackRun.command(['docker', 'compose', 'ps'])),
    start: const StackRun.command(['docker', 'compose', 'up', '--wait']),
    stop: const StackRun.command(['docker', 'compose', 'down']),
  ).config,
};

const _header = '''
<!-- Generated by app/tool/generate_capabilities.dart. Do not edit by hand. -->

# What flutterware can do

Every capability below is reachable from `fw` and from MCP, because both drive
the same `PluginCore`s through the same `Session.invoke`. The GUI adds a panel
over those cores; it does not add abilities.

Regenerate with:

```sh
cd app && dart run tool/generate_capabilities.dart
```
''';

/// The CLI, rendered from `fwCommands` — the same list `fw help` prints.
///
/// It used to be prose here *and* prose in `FwCli`, which is two copies of a
/// command summary and one drift away from a document describing a flag that
/// no longer exists.
String _cliSection() {
  var buffer = StringBuffer('''
## `fw`

```sh
cd app && dart run bin/fw.dart <command>
```

| command | what it does |
|---|---|
''');
  for (var command in fwCommands) {
    buffer.writeln('| `${mdCell(command.usage)}` | ${command.summary} |');
  }
  buffer.writeln();
  buffer.writeln('$fwHelpFooter\n');
  buffer.writeln('Exit codes:\n');
  for (var code in fwExitCodes.entries) {
    buffer.writeln('- `${code.key}` — ${code.value}');
  }
  return buffer.toString();
}

String _mcpSection() {
  var buffer = StringBuffer('''
## MCP

Point a client at `fw mcp`:

```json
{
  "mcpServers": {
    "flutterware": {
      "command": "dart", "args": ["run", "flutterware", "mcp"]
    }
  }
}
```

`fw init` writes that entry. The server uses whichever `dart` the client starts
it with. If the project pins its SDK with a version manager, prefix the
command, as in `fvm dart …`.

Inside a checkout of flutterware itself, `cd app && dart run bin/mcp.dart` is
the same server without the launcher in front of it.

Stdout carries the protocol. Logs and build output go to stderr.

''');
  for (var tool in FlutterwareMcpServer.tools) {
    buffer.writeln('### `${tool.name}`');
    buffer.writeln();
    buffer.writeln(tool.description ?? '');
    buffer.writeln();
    var properties = tool.inputSchema.properties ?? const {};
    if (properties.isEmpty) {
      buffer.writeln('Takes no arguments.');
      buffer.writeln();
      continue;
    }
    var required = tool.inputSchema.required ?? const [];
    buffer.writeln('| argument | required | |');
    buffer.writeln('|---|---|---|');
    for (var entry in properties.entries) {
      var description = (entry.value as Map<String, Object?>)['description'];
      buffer.writeln(
        '| `${entry.key}` | ${required.contains(entry.key) ? 'yes' : 'no'} '
        '| ${_cell(description as String?)} |',
      );
    }
    buffer.writeln();
  }
  return buffer.toString();
}

String _actionsSection(
  List<PluginCore> cores,
  Map<String, ResultShape> shapes,
) {
  var buffer = StringBuffer('## Plugins\n');
  for (var core in cores) {
    var report = core.report;
    buffer.writeln();
    buffer.writeln('### `${report.id}`');
    buffer.writeln();
    // Above the no-actions line as well as above the actions: a plugin with
    // nothing to invoke is the one whose id explains least.
    if (report.description case var description?) {
      buffer.writeln(description);
      buffer.writeln();
    }
    if (report.actions.isEmpty) {
      buffer.writeln('No actions.');
      continue;
    }
    if (authoringGuides[report.id] case var guide?) {
      buffer.writeln(guide.trim());
      buffer.writeln();
    }
    var short = report.id.split('.').last;
    for (var action in report.actions) {
      buffer.writeln('#### `${action.id}` — ${action.label}');
      buffer.writeln();
      if (action.description != null) {
        buffer.writeln('${action.description}\n');
      }
      buffer.writeln('```sh');
      buffer.writeln(FwCli.usageLine(short, action));
      buffer.writeln('```');
      buffer.writeln();
      if (action.returnsName case var returns?) {
        buffer.writeln('Returns `$returns`:\n');
        if (shapes[returns] case var shape?) {
          buffer.writeln('```');
          buffer.write(shape.toText());
          buffer.writeln('```');
          if (shape.gates) {
            buffer.writeln();
            buffer.writeln(gatingNote);
          }
        } else {
          // Its `toJson` is hand-written, so its fields are not its keys and
          // nothing here can honestly claim to know them.
          buffer.writeln(
            'Shape not published: `$returns` writes its own `toJson`, so its '
            'fields are not its keys.',
          );
        }
        buffer.writeln();
      }
      if (action.parameters.isEmpty) {
        buffer.writeln('Takes no parameters.');
        buffer.writeln();
        continue;
      }
      buffer.writeln('| parameter | kind | required | default | |');
      buffer.writeln('|---|---|---|---|---|');
      for (var parameter in action.parameters) {
        buffer.writeln(
          '| `${parameter.id}` | ${_kind(parameter)} '
          '| ${parameter.required ? 'yes' : 'no'} '
          '| ${_cell(parameter.defaultValue)} '
          '| ${_cell(parameter.description)} |',
        );
      }
      buffer.writeln();
    }
  }
  return buffer.toString();
}

/// Where a `choice` gets its legal values, since the values themselves are
/// project data and change per project.
String _kind(ActionParameter parameter) {
  if (parameter.kind != ActionParameterKind.choice) return parameter.kind.name;
  if (parameter.optionsFrom case var from?) return 'choice (from `$from`)';
  return 'choice';
}

String _cell(String? value) =>
    value == null || value.isEmpty ? '—' : mdCell(value);

/// One cell of a markdown table, with the pipes that would end it escaped.
///
/// The rule was already here for parameter descriptions; the usage column was
/// the one place it was not applied, and `capture` had been rendering as three
/// columns since it grew a `--theme=light|dark`.
///
/// Public so the test that the document and `fw help` agree can compare against
/// what the renderer actually writes, rather than restating this rule.
String mdCell(String text) => text.replaceAll('|', r'\|');
